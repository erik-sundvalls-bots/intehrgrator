function modelWithSlots(slots: Array<{ slotId: string; expression: string; label?: string }>): MappingModel {
  let model = createEmptyModel("test-template");
  for (const s of slots) {
    model = applyExpressionEdit(model, s.slotId, s.expression, {
      rmType: "DV_TEXT",
      returnType: "string",
      label: s.label,
    });
  }
  return model;
}

function xmlNoteWithQuery(path: string) {
  return {
    type: "xml_element",
    fields: { NAME: "Note" },
    extraState: { childGroups: ["attributes", "children"] },
    inputs: {
      VALUE: {
        block: {
          type: "xml_text",
          inputs: {
            VALUE: {
              block: { type: "source_query", fields: { EXPRESSION: path } },
            },
          },
        },
      },
    },
  };
}

